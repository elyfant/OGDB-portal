#!/usr/bin/env python3
"""Embed the glider part drawings in the dashboard.

Usage:
    python3 dashboard/scripts/build_glider_parts.py

Reads every dashboard/src/lib/glider-diagram/<platform>/*.svg and writes
<platform>/parts.generated.ts, which the diagram component imports.

The .svg files are the source of truth: draw or edit them in Inkscape (or any
SVG editor), then re-run this script. They are embedded as TypeScript
strings rather than served as files because the dashboard's Docker image
doesn't ship a public/ folder.

Rules for a part drawing:
  * the root <svg> has a viewBox of "0 0 W H" (its size, in deck units --
    1/100 inch, matching the other parts so they stay in proportion),
  * ids inside it (gradients, clip paths) are prefixed with the part name,
    since every part ends up inline in one shared <svg> and ids are global,
  * draw inside the viewBox (inset strokes by ~1 unit); nothing is clipped
    to it when embedded, but a standalone preview is.

Standard library only.
"""

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / "src/lib/glider-diagram"


def build(platform_dir: Path) -> None:
    parts = {}
    for svg in sorted(platform_dir.glob("*.svg")):
        text = svg.read_text()
        m = re.search(r"<svg\b[^>]*\bviewBox=\"0 0 ([\d.]+) ([\d.]+)\"[^>]*>", text)
        if not m:
            raise SystemExit(f'{svg.name}: root <svg> needs viewBox="0 0 W H"')
        inner = text[m.end() : text.rindex("</svg>")].strip()
        parts[svg.stem] = (float(m.group(1)), float(m.group(2)), inner)

    lines = [
        "// GENERATED by dashboard/scripts/build_glider_parts.py -- do not edit.",
        "// Edit the .svg files next to this one and re-run the script. (Excluded from",
        "// Biome in biome.json, since the generator writes long single-line strings.)",
        "",
        "export interface DiagramPart {",
        "\t/** Size in deck units (1/100 inch). */",
        "\twidth: number;",
        "\theight: number;",
        "\t/** SVG markup, origin at the part's top-left. */",
        "\tsvg: string;",
        "}",
        "",
        "export const PARTS: Record<string, DiagramPart> = {",
    ]
    for pid, (w, h, inner) in parts.items():
        lines.append(
            f"\t{pid}: {{ width: {w:g}, height: {h:g}, svg: {json.dumps(inner)} }},"
        )
    lines.append("};")
    (platform_dir / "parts.generated.ts").write_text("\n".join(lines) + "\n")
    print(f"{platform_dir.name}: embedded {len(parts)} parts")


for d in sorted(p for p in ROOT.iterdir() if p.is_dir()):
    build(d)
